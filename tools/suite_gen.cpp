// Генератор golden-значений suite v1 (не входит в бинарь бенчмарка).
//
// Считает каждый тест каждой категории и каждый диапазон verify эталонным
// CPU-исполнителем и печатает значения для src/suite_v1.h. Независимые
// проверки: цифры BBP-окон сверяются со встроенным reference/pi_hex.txt, число
// простых окон MR — с сегментированным решетом Эратосфена (--sieve).
//
//   monkey_suite_gen [--sieve] [--verify-only]

