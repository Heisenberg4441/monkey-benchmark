namespace {

uint64_t isqrt(uint64_t x) {
    auto r = static_cast<uint64_t>(std::sqrt(static_cast<double>(x)));
    while (r * r > x) --r;
    while ((r + 1) * (r + 1) <= x) ++r;
    return r;
}

// Число простых среди нечётных base + 2i, i < count. Базовые простые — решето
// по нечётным до sqrt(верхней границы) (битовый массив), окно — параллельно.
uint64_t sieve_count_odd(uint64_t base, uint64_t count) {
    const uint64_t hi = base + 2 * count;
    const uint64_t root = isqrt(hi) + 1;
    std::vector<uint64_t> bits((root / 2) / 64 + 1, 0); // бит k — число 2k+1 составное
    for (uint64_t p = 3; p * p <= root; p += 2)
        if (!(bits[(p / 2) / 64] >> ((p / 2) % 64) & 1))
            for (uint64_t m = p * p; m <= root; m += 2 * p) bits[(m / 2) / 64] |= 1ull << ((m / 2) % 64);
    std::vector<uint32_t> primes;
    for (uint64_t p = 3; p <= root; p += 2)
        if (!(bits[(p / 2) / 64] >> ((p / 2) % 64) & 1)) primes.push_back(static_cast<uint32_t>(p));

    const unsigned T = std::max(1u, std::thread::hardware_concurrency());
    std::atomic<uint64_t> total{0};
    std::vector<std::thread> pool;
    const uint64_t seg = (count + T - 1) / T;
    for (unsigned t = 0; t < T; ++t) {
        pool.emplace_back([&, t] {
            const uint64_t i0 = t * seg, i1 = std::min(count, i0 + seg);
            if (i0 >= i1) return;
            std::vector<uint8_t> comp(i1 - i0, 0); // индекс i — число base + 2i
            const uint64_t lo = base + 2 * i0;
            for (uint32_t p : primes) {
                // Первое нечётное кратное p, не меньшее lo (и не меньшее p^2).
                uint64_t m = (lo + p - 1) / p * p;
                if ((m & 1) == 0) m += p;
                if (m < static_cast<uint64_t>(p) * p) m = static_cast<uint64_t>(p) * p;
                for (; m < base + 2 * i1; m += 2 * static_cast<uint64_t>(p)) comp[(m - lo) / 2] = 1;
            }
            uint64_t n = 0;
            for (uint8_t c : comp) n += !c;
            total += n;
        });
    }
    for (auto& th : pool) th.join();
    return total;
}

} // namespace

int main(int argc, char** argv) {
    bool sieve = false, verify_only = false;
    for (int i = 1; i < argc; ++i) {
        sieve |= std::strcmp(argv[i], "--sieve") == 0;
        verify_only |= std::strcmp(argv[i], "--verify-only") == 0;
    }
    const unsigned threads = std::max(1u, std::thread::hardware_concurrency());
    Engine e(threads, nullptr);
    std::printf("// suite v%d golden, generated by tools/suite_gen.cpp\n", kVersion);
    bool ok = true;
    for (int ti = 0; ti < kTestCount && !verify_only; ++ti) {
        const TestDef& t = kTests[ti];
        std::printf("// %s\n", t.name);
        for (int c = 0; c < kCategories; ++c) {
            const auto cat = static_cast<Category>(c);
            const KernelParams kp = make_params(t, cat);
            JobSpec s;
            s.kp = &kp;
            s.end = work_units(t, cat);
            const auto t0 = std::chrono::steady_clock::now();
            const JobResult r = e.run(s);
            const double dt = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
            std::string note;
            if (!r.completed) {
                note = " ERROR " + r.error;
                ok = false;
            }
            if (t.kernel == KernelId::Bbp) {
                const BbpVerdict v = bbp_verify(kp.bbp, r.bbp_acc);
                note += v.bad_positions ? " PI MISMATCH " + std::to_string(v.bad_positions) : " pi digits ok";
                ok = ok && v.bad_positions == 0;
            }
            if (t.kernel == KernelId::MillerRabin && sieve) {
                const uint64_t primes = sieve_count_odd(kp.mr_base, s.end);
                note += primes == r.res.hits ? " sieve ok" : " SIEVE MISMATCH " + std::to_string(primes);
                ok = ok && primes == r.res.hits;
            }
            std::printf("    {0x%016llxull, %lluull}, // %s, %.1f s%s\n",
                        static_cast<unsigned long long>(r.res.checksum),
                        static_cast<unsigned long long>(r.res.hits), category_key(cat), dt, note.c_str());
            std::fflush(stdout);
        }
    }
    std::printf("// verify\n");
    for (const VerifyCase& vc : kVerify) {
        const KernelParams kp = make_params(kTests[vc.test], vc.category);
        JobSpec s;
        s.kp = &kp;
        s.begin = vc.begin;
        s.end = vc.begin + vc.count;
        const JobResult r = e.run(s);
        ok = ok && r.completed;
        std::printf("    {0x%016llxull, %lluull}, // %s [%llu, +%llu)\n",
                    static_cast<unsigned long long>(r.res.checksum), static_cast<unsigned long long>(r.res.hits),
                    kTests[vc.test].name, static_cast<unsigned long long>(vc.begin),
                    static_cast<unsigned long long>(vc.count));
    }
    return ok ? 0 : 1;
}
